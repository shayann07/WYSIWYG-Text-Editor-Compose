"""Generate shared JVM/JS conformance cases from the pinned Unicode 16 witness."""
from pathlib import Path
import hashlib

ROOT = Path(__file__).resolve().parents[2]
FIXTURES = ROOT / 'tests/desktop-harness/src/jvmMain/resources/unicode'


def main():
    name = 'GraphemeBreakTest-16.0.0.txt'
    properties = dict(line.split('=', 1) for line in (FIXTURES / 'hashes.properties').read_text().splitlines() if '=' in line)
    raw = (FIXTURES / name).read_bytes()
    assert hashlib.sha256(raw).hexdigest() == properties[name]
    rows = [line.split('#')[0].strip() for line in raw.decode('utf-8').splitlines()]
    rows = [row for row in rows if row]
    chunks = [rows[i:i + 100] for i in range(0, len(rows), 100)]
    source = '''// Generated by tooling/unicode/generate_conformance.py; do not edit by hand.
package dev.shayxo.composedoc.model

import kotlin.test.Test
import kotlin.test.assertEquals

class Unicode16ConformanceTest {
    @Test
    fun allPinnedGraphemeBreakCases() {
        for (row in cases().flatMap { it.lines() }.filter { it.isNotBlank() }) {
            val text = StringBuilder()
            val expected = mutableListOf<Int>()
            for (part in row.trim().split(Regex("\\\\s+"))) {
                when (part) {
                    "÷" -> expected.add(text.length)
                    "×" -> Unit
                    else -> {
                        val point = part.toInt(16)
                        if (point <= 0xFFFF) text.append(point.toChar()) else {
                            val scalar = point - 0x10000
                            text.append((0xD800 + (scalar shr 10)).toChar())
                            text.append((0xDC00 + (scalar and 0x3FF)).toChar())
                        }
                    }
                }
            }
            assertEquals(expected, Graphemes.stops(text.toString()).toList(), row)
        }
    }

    private fun cases(): List<String> = listOf(
'''
    source += ',\n'.join('        """\n' + '\n'.join(chunk) + '\n"""' for chunk in chunks)
    source += '\n    )\n}\n'
    destination = ROOT / 'core/model/src/commonTest/kotlin/dev/shayxo/composedoc/model/Unicode16ConformanceTest.kt'
    destination.write_text(source, encoding='utf-8')
    print(f'Generated {len(rows)} pinned Unicode 16 cases')


if __name__ == '__main__':
    main()
